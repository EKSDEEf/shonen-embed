import { readFile, writeFile } from 'node:fs/promises';

// Ship one classic script so the generator also works from file:// without imports.
const root = new URL('../', import.meta.url);
const helpers = (await readFile(new URL('examples/integration.mjs', root), 'utf8')).replace(/^export /gm, '');
const example = (await readFile(new URL('examples/example.mjs', root), 'utf8')).replace(/^import .* from '\.\/integration\.mjs';\r?\n/, '');
await writeFile(new URL('examples/example.js', root), '// Generated by scripts/build-example.mjs. Edit the .mjs source files, then rebuild.\n(function () {\n\'use strict\';\n' + helpers + '\n' + example + '\n})();\n');
console.log('Built examples/example.js (no module loading or dependencies).');